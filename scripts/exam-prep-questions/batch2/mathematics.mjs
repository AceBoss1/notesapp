const close = (a, b) => Math.abs(a - b) < 1e-9;
const near = (a, b, tol) => Math.abs(a - b) < tol;
const deg = (r) => (r * 180) / Math.PI;
const rad = (d) => (d * Math.PI) / 180;
const gcd = (a, b) => (b ? gcd(b, a % b) : Math.abs(a));
const lcm = (a, b) => (a * b) / gcd(a, b);
const fact = (n) => (n <= 1 ? 1 : n * fact(n - 1));
const nCr = (n, r) => fact(n) / (fact(r) * fact(n - r));
// Exact fraction n/d in lowest terms, written the way the options are ("3/10", "−1/3", "2").
const fr = (n, d) => {
  const g = gcd(n, d);
  let [p, q] = [n / g, d / g];
  if (q < 0) [p, q] = [-p, -q];
  const s = q === 1 ? `${Math.abs(p)}` : `${Math.abs(p)}/${q}`;
  return p < 0 ? `−${s}` : s;
};
// Numerical derivative and integral, used to confirm calculus answers.
const dydx = (f, x) => (f(x + 1e-6) - f(x - 1e-6)) / 2e-6;
const integ = (f, a, b, n = 1000) => {
  const h = (b - a) / n;
  let s = f(a) + f(b);
  for (let i = 1; i < n; i++) s += (i % 2 ? 4 : 2) * f(a + i * h);
  return (s * h) / 3;
};
