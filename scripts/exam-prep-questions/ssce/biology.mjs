const close = (a, b) => Math.abs(a - b) < 1e-9;
// Fraction of offspring from a cross of two parents (arrays of alleles) whose genotype passes `test`.
const cross = (p1, p2, test) => {
  let hit = 0, all = 0;
  for (const a of p1) for (const b of p2) { all += 1; if (test(a + b)) hit += 1; }
  return hit / all;
};

