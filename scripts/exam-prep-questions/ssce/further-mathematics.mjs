const near = (a, b, tol) => Math.abs(a - b) < tol;
const is = (q, value) => ({ ...q, check: q.o[0] === value });
const deg = (rad) => (rad * 180) / Math.PI;
const gcd = (a, b) => { a = Math.abs(a); b = Math.abs(b); while (b) [a, b] = [b, a % b]; return a; };
// Exact fractions as [numerator, denominator].
const fr = (n, d = 1) => { if (d < 0) { n = -n; d = -d; } const g = gcd(n, d) || 1; return [n / g, d / g]; };
const add = (a, b) => fr(a[0] * b[1] + b[0] * a[1], a[1] * b[1]);
const sub = (a, b) => fr(a[0] * b[1] - b[0] * a[1], a[1] * b[1]);
const mul = (a, b) => fr(a[0] * b[0], a[1] * b[1]);
const div = (a, b) => fr(a[0] * b[1], a[1] * b[0]);
const fs = (f) => { const [n, d] = fr(f[0], f[1]); return (n < 0 ? "−" : "") + Math.abs(n) + (d === 1 ? "" : `/${d}`); };
const eq = (a, b) => { const x = fr(a[0], a[1]), y = fr(b[0], b[1]); return x[0] === y[0] && x[1] === y[1]; };
const num = (x) => (x < 0 ? "−" : "") + Math.abs(x);
const fact = (n) => (n <= 1 ? 1 : n * fact(n - 1));
const C = (n, r) => fact(n) / (fact(r) * fact(n - r));
const det2 = (m) => m[0][0] * m[1][1] - m[0][1] * m[1][0];
const det3 = (m) => m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1]) - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0]) + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]);
const dydx = (f, x, h = 1e-5) => (f(x + h) - f(x - h)) / (2 * h);
const same = (f, g, xs) => xs.every((x) => near(f(x), g(x), 1e-6));
